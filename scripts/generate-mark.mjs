// Builds the QRCode666 brand mark: a real, scannable QR code for
// https://qrcode666.app (error correction H) with azure finder centres and a
// "666" plate in the middle, written as static vector data to
// src/brand/mark.ts. Run with `node scripts/generate-mark.mjs`.
// tests/unit/brand.test.ts proves the result decodes with jsQR and ZXing.
import { writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'

const require = createRequire(import.meta.url)
const { create } = require('qrcode/lib/core/qrcode.js')

const URL_TEXT = 'https://qrcode666.app'
const qr = create(URL_TEXT, { errorCorrectionLevel: 'H' })
const n = qr.modules.size
const dark = (r, c) => r >= 0 && c >= 0 && r < n && c < n && qr.modules.data[r * n + c] === 1
const finder = (r, c) => (r < 7 && c < 7) || (r < 7 && c >= n - 7) || (r >= n - 7 && c < 7)

// The "666" plate: a whole-module rectangle in the centre, cleared to white.
const PLATE_W = 13
const PLATE_H = 7
const G = 1 // glyph scale, in modules
const px0 = Math.round((n - PLATE_W) / 2)
const py0 = Math.round((n - PLATE_H) / 2)
const inPlate = (r, c) => c >= px0 && c < px0 + PLATE_W && r >= py0 && r < py0 + PLATE_H

// Data modules as merged horizontal runs.
let modules = ''
for (let r = 0; r < n; r++) {
  let c = 0
  while (c < n) {
    if (!dark(r, c) || finder(r, c) || inPlate(r, c)) {
      c++
      continue
    }
    const s = c
    while (c < n && dark(r, c) && !finder(r, c) && !inPlate(r, c)) c++
    modules += `M${s} ${r}h${c - s}v1h${s - c}z`
  }
}

let rings = ''
let centres = ''
for (const [x, y] of [
  [0, 0],
  [n - 7, 0],
  [0, n - 7],
]) {
  rings += `M${x} ${y}h7v7h-7zM${x + 1} ${y + 1}v5h5v-5z`
  centres += `M${x + 2} ${y + 2}h3v3h-3z`
}

// One "6": a stroked bowl with a rising tail, and an azure dot in the bowl.
// Units are modules; the glyph is ~5 modules tall.
const R = 1.25 * G
const glyph = (cx, cy) =>
  `M${fx(cx - R)} ${cy}a${fx(R)} ${fx(R)} 0 1 0 ${fx(2 * R)} 0a${fx(R)} ${fx(R)} 0 1 0 ${fx(-2 * R)} 0` +
  `C${fx(cx - R)} ${fx(cy - 1.7 * G)} ${fx(cx - 0.4 * G)} ${fx(cy - 2.75 * G)} ${fx(cx + 0.95 * G)} ${fx(cy - 3.05 * G)}`
const fx = (v) => Math.round(v * 1000) / 1000
const midX = px0 + PLATE_W / 2
const bowlY = py0 + PLATE_H / 2 + 0.85 * G
const step = 3.75 * G
let sixes = ''
const dots = []
for (const dx of [-step, 0, step]) {
  sixes += glyph(fx(midX + dx), fx(bowlY))
  dots.push([fx(midX + dx), fx(bowlY)])
}

const out = `// Generated by scripts/generate-mark.mjs — do not edit by hand.
/**
 * The QRCode666 mark is itself a working QR code: it encodes
 * ${URL_TEXT} (error correction H, version ${qr.version}), with azure finder
 * centres and a "666" plate in the middle. Kept dependency-free so the asset
 * script can import it directly. tests/unit/brand.test.ts verifies it scans.
 */

export const MARK_URL = '${URL_TEXT}'
export const MARK_SIZE = ${n}
export const MARK_MODULES = '${modules}'
export const MARK_RINGS = '${rings}'
export const MARK_CENTRES = '${centres}'
export const MARK_PLATE = { x: ${px0}, y: ${py0}, w: ${PLATE_W}, h: ${PLATE_H} }
export const MARK_SIXES = '${sixes}'
export const MARK_DOTS: [number, number][] = ${JSON.stringify(dots)}
export const MARK_STROKE = ${fx(0.72 * G)}
export const MARK_DOT_R = ${fx(0.52 * G)}

/**
 * Brand blue. The original artwork used azure #019eff, but as a finder-centre
 * colour it reads as mid-grey to a camera and made jsQR miss ~15% of sizes;
 * this electric blue (also the site accent) scans at every size we test.
 */
export const BRAND_BLUE = '#1d4bff'
export const ACCENT = BRAND_BLUE

/** The mark's inner SVG markup in module units (no <svg> wrapper). */
export function markBody({ fg = '#000000', blue = BRAND_BLUE, paper = '#ffffff' } = {}): string {
  const p = MARK_PLATE
  return (
    \`<path d="\${MARK_MODULES}" fill="\${fg}"/>\` +
    \`<path d="\${MARK_RINGS}" fill="\${fg}" fill-rule="evenodd"/>\` +
    \`<path d="\${MARK_CENTRES}" fill="\${blue}"/>\` +
    \`<rect x="\${p.x}" y="\${p.y}" width="\${p.w}" height="\${p.h}" fill="\${paper}"/>\` +
    \`<path d="\${MARK_SIXES}" fill="none" stroke="\${fg}" stroke-width="\${MARK_STROKE}" stroke-linecap="round"/>\` +
    MARK_DOTS.map(([x, y]) => \`<circle cx="\${x}" cy="\${y}" r="\${MARK_DOT_R}" fill="\${blue}"/>\`).join('')
  )
}

/** Standalone SVG of the mark on white, e.g. for favicons and avatars. */
export function markSvg({ padding = 2, radius = 0, background = '#ffffff' } = {}): string {
  const s = MARK_SIZE + padding * 2
  return (
    \`<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 \${s} \${s}">\` +
    \`<rect width="\${s}" height="\${s}" rx="\${radius}" fill="\${background}"/>\` +
    \`<g transform="translate(\${padding} \${padding})">\${markBody()}</g></svg>\`
  )
}
`
writeFileSync(new URL('../src/brand/mark.ts', import.meta.url), out)
console.log(`mark: version ${qr.version}, ${n}×${n}, plate ${PLATE_W}×${PLATE_H} at (${px0},${py0})`)
